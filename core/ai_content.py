def prompt_item():
    return random.choice(AI_PROMPTS)


def comparison_item():
    return random.choice(AI_COMPARISONS)


def question_item():
    return random.choice(AI_QUESTIONS)


def caption_for(tpl, data, shop_name="", extra_tags=()):
    """کپشن برای هر نوع محتوا"""
    tags = ai_hashtags(shop_name, extra_tags)
    tag_text = " ".join(tags)
    if tpl == "fact":
        title, desc = data
        cap = f"🧠 دانستنی هوش مصنوعی:\n{title}\n\n{desc}\n\n💬 نظرت درباره این یکی چی بود؟ کامنت کن!\n\n{tag_text}"
    elif tpl == "tool":
        name, emoji, desc, price, use = data
        cap = (f"{emoji} معرفی ابزار: {name}\n\n{desc}\n\n💳 هزینه: {price}\n"
               f"🎯 بهترین کاربرد: {use}\n\nامتحانش کردی؟ تجربه‌ات را بنویس 👇\n\n{tag_text}")
    elif tpl == "prompt":
        name, prompt = data
        cap = (f"✨ پرامپت امروز: {name}\n\nاین پرامپت را کپی کن و داخل ChatGPT یا Claude بچسبان:\n"
               f"👇👇👇\n{prompt}\n\n📌 ذخیره‌اش کن که گم نشود!\n\n{tag_text}")
    elif tpl == "comparison":
        a, b, a_desc, b_desc, verdict = data
        cap = (f"⚔️ مقایسه هوش مصنوعی:\n{a} در برابر {b}\n\n{a}: {a_desc}\n{b}: {b_desc}\n\n"
               f"💡 جمع‌بندی: {verdict}\n\nشما کدام را ترجیح می‌دهید؟ 👇\n\n{tag_text}")
    else:  # question
        cap = f"❓ سوال امروز:\n{data}\n\nجواب‌ها را می‌خوانیم! 👇\n\n{tag_text}"
    return cap, tag_text
